// Writes one small entry file for each action manifest. Each entry turns on the V8 compile
// cache, imports the shared bundle in dist/lib, and calls the function of its action. The
// compile cache is best effort: a failure to turn it on never fails the step. `npm run build`
// runs this file after ncc, so a build gives the same bytes each time.
//
// The entry makes the cache directory and checks that it can write there before it turns on the
// cache. For a path under /proc, Node 24.22 loops forever in enableCompileCache, and also in
// mkdirSync with `recursive: true`. A mkdirSync without `recursive` throws for such a path, so
// the entry makes only the last directory. When a check fails, the step runs without the cache.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ENTRIES: Record<string, string> = {
  restore: 'runRestore',
  save: 'runSave',
  'restore-only': 'runRestoreOnly',
  'save-only': 'runSaveOnly',
  prune: 'runPrune',
  inspect: 'runInspect',
};

function entryBody(fn: string): string {
  return `// Generated by scripts/writeEntries.ts. Do not edit.
import fs from 'node:fs';
import module from 'node:module';
import os from 'node:os';
import path from 'node:path';

try {
  const dir = path.join(process.env.RUNNER_TEMP || os.tmpdir(), 'cloud-cache-action-v8');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir);
  fs.accessSync(dir, fs.constants.W_OK);
  module.enableCompileCache?.(dir);
} catch {}
const { ${fn} } = await import('../lib/index.js');
${fn}(true);
`;
}

const dist = join(import.meta.dirname, '..', 'dist');
for (const [name, fn] of Object.entries(ENTRIES)) {
  const dir = join(dist, name);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.js'), entryBody(fn));
  writeFileSync(join(dir, 'package.json'), '{\n  "type": "module"\n}\n');
}
