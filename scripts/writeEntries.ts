// Writes one small entry file for each action manifest. Each entry imports the shared
// bundle in dist/lib and calls the function of its action. `npm run build` runs this file
// after ncc, so a build gives the same bytes each time.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ENTRIES: Record<string, string> = {
  restore: 'runRestore',
  save: 'runSave',
  'restore-only': 'runRestoreOnly',
  'save-only': 'runSaveOnly',
  prune: 'runPrune',
  inspect: 'runInspect',
};

const dist = join(import.meta.dirname, '..', 'dist');
for (const [name, fn] of Object.entries(ENTRIES)) {
  const dir = join(dist, name);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, 'index.js'),
    `// Generated by scripts/writeEntries.ts. Do not edit.\nimport { ${fn} } from '../lib/index.js';\n\n${fn}(true);\n`
  );
  writeFileSync(join(dir, 'package.json'), '{\n  "type": "module"\n}\n');
}
